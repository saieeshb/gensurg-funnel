  /* ---------------- fill inline figures from the data ---------------- */
  function inlineNumbers() {
    document.querySelectorAll('[data-val]').forEach(n => {
      const v = n.getAttribute('data-val').split('.').reduce((o, k) => (o || {})[k], D);
      if (v !== undefined && v !== null) n.textContent = typeof v === 'number' ? fmt(v, n.dataset.dp ? +n.dataset.dp : (Number.isInteger(v) ? 0 : 1)) : v;
    });
  }

  /* ---------------- the one authored motion moment ----------------
     Only the instrument animates: its range bands sweep out and its index
     marks drop in, once, when it first comes into view.                  */
  function reveal() {
    const inst = document.querySelectorAll('.instrument');
    if (!inst.length) return;
    if (matchMedia('(prefers-reduced-motion: reduce)').matches) {
      inst.forEach(n => n.classList.add('in'));
      return;
    }
    const io = new IntersectionObserver((es) => es.forEach(e => {
      if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); }
    }), { rootMargin: '0px 0px -8% 0px', threshold: 0.06 });
    inst.forEach(n => io.observe(n));
  }

  /* ---------------- theme toggle ---------------- */
  function theme() {
    const btn = $('#theme');
    if (!btn) return;
    const sys = () => matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
    const apply = t => {
      document.documentElement.setAttribute('data-theme', t);
      btn.textContent = t === 'dark' ? 'Light' : 'Dark';
      btn.setAttribute('aria-label', `Switch to ${t === 'dark' ? 'light' : 'dark'} theme`);
    };
    apply(localStorage.getItem('theme') || sys());
    btn.addEventListener('click', () => {
      const t = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
      localStorage.setItem('theme', t); apply(t);
    });
  }

